CREATE TABLE analysis_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_code VARCHAR(16) NOT NULL,
    stock_name VARCHAR(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    duration_ms BIGINT,
    market_report TEXT,
    news_report TEXT,
    social_report TEXT,
    fundamental_report TEXT,
    bull_arguments TEXT,
    bear_arguments TEXT,
    research_decision TEXT,
    trade_decision TEXT,
    risk_debate TEXT,
    final_decision TEXT,
    recalled_memories TEXT,
    model_provider VARCHAR(30),
    quick_model VARCHAR(100),
    deep_model VARCHAR(100),
    total_tokens INTEGER DEFAULT 0,
    status VARCHAR(20) DEFAULT 'RUNNING',
    stage VARCHAR(50),
    state_snapshot TEXT
);
CREATE INDEX idx_report_stock ON analysis_report(stock_code, created_at DESC);

CREATE TABLE trading_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    balance NUMERIC(28,8) NOT NULL CHECK (balance >= 0),
    frozen NUMERIC(28,8) NOT NULL DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
