CREATE TABLE trade_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES trading_account(id),
    stock_code VARCHAR(16) NOT NULL,
    direction VARCHAR(4) NOT NULL CHECK (direction IN ('BUY', 'SELL')),
    price NUMERIC(28,8) NOT NULL CHECK (price > 0),
    quantity NUMERIC(28,8) NOT NULL CHECK (quantity > 0),
    amount NUMERIC(28,8) NOT NULL,
    fee NUMERIC(28,8) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'FILLED',
    analysis_id BIGINT REFERENCES analysis_report(id) ON DELETE SET NULL,
    remark VARCHAR(200),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (account_id, analysis_id)
);
CREATE INDEX idx_order_account ON trade_order(account_id, created_at DESC);

CREATE TABLE trade_position (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES trading_account(id),
    stock_code VARCHAR(16) NOT NULL,
    quantity NUMERIC(28,8) NOT NULL CHECK (quantity > 0),
    avg_cost NUMERIC(28,8) NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (account_id, stock_code)
);

CREATE TABLE model_provider (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    type VARCHAR(20) NOT NULL,
    base_url VARCHAR(500),
    api_key_env_var VARCHAR(100),
    model_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE agent_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id VARCHAR(50) NOT NULL UNIQUE,
    display_name VARCHAR(50) NOT NULL,
    provider_id VARCHAR(50),
    model_name VARCHAR(100),
    execution_order INTEGER DEFAULT 0,
    is_deep BOOLEAN DEFAULT FALSE
);

CREATE TABLE pipeline_node (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_key VARCHAR(50) NOT NULL UNIQUE,
    display_name VARCHAR(50) NOT NULL,
    context_type VARCHAR(30) NOT NULL,
    system_prompt TEXT,
    stage_order INTEGER NOT NULL,
    position_in_stage INTEGER NOT NULL,
    provider_id VARCHAR(50),
    model_name VARCHAR(100),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    stage_type VARCHAR(20) NOT NULL DEFAULT 'AUTO',
    debate_rounds INTEGER NOT NULL DEFAULT 2
);

CREATE TABLE chat_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES chat_session(id),
    role VARCHAR(10) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_chat_session ON chat_message(session_id, created_at);
